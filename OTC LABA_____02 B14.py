import turtle  # Подключаем графический модуль "Черепашка" для рисования


# Функция конечного автомата, которая управляет поведением черепашки на каждом шаге
def perform_switch_case(state, t, turn):
    x = round(t.position()[0] / 10)  # Получаем координату X, делим на 10 и округляем до шагов сетки
    y = round(t.position()[1] / 10)  # Получаем координату Y, делим на 10 и округляем до шагов сетки
    num_turns = 2  # Задаем жесткий лимит: алгоритм должен сделать ровно 2 полных витка змейки

    # Если у объекта черепашки ещё нет локального счетчика шагов вверх, создаем его со значением 0
    if not hasattr(t, "up_steps"):
        t.up_steps = 0

    # Состояние инициализации (самый первый запуск программы)
    if state == "INIT":
        if True:  # Техническое условие, которое всегда истинно
            state = "RIGHT"  # Переключаем автомат в состояние движения вправо
            t.setheading(0)  # Разворачиваем голову черепашки на восток (вправо)
            return state, turn  # Возвращаем новые параметры и выходим из функции
        return state, turn  # Резервный возврат параметров

    # Состояние движения вправо
    if state == "RIGHT":
        t.forward(10)  # Черепашка делает один шаг вперед на 10 пикселей
        # Проверяем, дошла ли черепашка до правой суженной границы (x = 5, то есть 50 пикселей)
        if x >= 5:
            # Если 2 витка уже полностью позади, пора финишировать на этой линии
            if turn > num_turns:
                state = "STOP"  # Переключаем в состояние остановки
                return state, turn  # Возвращаем параметры для завершения цикла draw()
            state = "UP"  # Если лимит не исчерпан, переключаем состояние на движение вверх
            t.setheading(90)  # Разворачиваем черепашку строго вверх
            t.up_steps = 0  # Сбрасываем счетчик вертикальных шагов для нового подъема
            return state, turn  # Возвращаем параметры и выходим из функции
        return state, turn  # Если граница x=5 еще не достигнута, продолжаем идти вправо

    # Состояние движения влево
    if state == "LEFT":
        t.forward(10)  # Черепашка делает один шаг вперед на 10 пикселей (направлена влево)
        # Проверяем, дошла ли черепашка до левой суженной границы (x = -5, то есть -50 пикселей)
        if x <= -5:
            state = "UP"  # Переключаем состояние на движение вверх
            turn = turn + 1  # Текущий полный виток змейки завершен, увеличиваем счетчик на 1
            t.setheading(90)  # Разворачиваем черепашку строго вверх
            t.up_steps = 0  # Сбрасываем счетчик вертикальных шагов для нового подъема
            return state, turn  # Возвращаем параметры и выходим из функции
        return state, turn  # Если граница x=-5 еще не достигнута, продолжаем идти влево

    # Состояние движения вверх
    if state == "UP":
        t.forward(10)  # Черепашка делает один шаг вверх на 10 пикселей
        t.up_steps += 1  # Увеличиваем внутренний счетчик вертикальных шагов на 1

        # Проверяем, поднялись ли мы ровно на 3 шага (30 пикселей) для идеального промежутка
        if t.up_steps >= 3:
            # Если координата x положительная, значит мы поднимались по правой стороне змейки
            if x > 0:
                state = "LEFT"  # Переключаем состояние на движение влево
                t.setheading(180)  # Разворачиваем черепашку строго влево
            # Если координата x отрицательная или нулевая (поднимались по левой стороне)
            else:
                state = "RIGHT"  # Переключаем состояние на движение вправо
                t.setheading(0)  # Разворачиваем черепашку строго вправо
            return state, turn  # Возвращаем измененные параметры в цикл
        return state, turn  # Если 3 шага вверх еще не сделано, продолжаем подниматься

    # Резервное неиспользуемое состояние движения вниз
    if state == "DOWN":
        t.forward(10)  # Перемещение вперед на 10 пикселей
        return state, turn  # Возврат параметров
    return state, turn  # Финальный безопасный возврат функции


# Главная функция, настраивающая экран и запускающая цикл рисования
def draw():
    start_state = "INIT"  # Задаем начальное состояние автомата
    end_state = "STOP"  # Задаем конечное состояние, при котором цикл завершится
    curr_state = start_state  # Записываем стартовое состояние в переменную текущего состояния
    
    t = turtle.Turtle()  # Создаем новый графический объект черепашки
    t.speed(0)  # Устанавливаем максимальную (мгновенную) скорость отрисовки
    t.pensize(1)  # Делаем толщину линии тонкой (1 пиксель), чтобы рисунок не был жирным
    t.shape("arrow")  # Задаем форму курсора в виде классической стрелочки

    t.penup()  # Поднимаем перо, чтобы переместиться без рисования линий
    t.goto(-60, -60)  # Переносим черепашку в начальную точку (с учетом запаса на первый шаг)
    t.pendown()  # Опускаем перо, теперь черепашка будет оставлять след на холсте

    turn = 1  # Задаем начальное значение счетчика витков змейки

    # Цикл работает до тех пор, пока состояние автомата не изменится на "STOP"
    while curr_state != end_state:
        # Вызываем автомат, передавая параметры, и перезаписываем их новыми значениями
        curr_state, turn = perform_switch_case(curr_state, t, turn)

    turtle.done()  # Фиксируем окно с готовым рисунком, чтобы оно не закрывалось само по себе


# Стандартная проверка: если файл запущен как основная программа, а не импортирован
if __name__ == "__main__":
    draw()  # Вызываем главную функцию для отрисовки змейки
